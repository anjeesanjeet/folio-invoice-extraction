"""Automated flowcharts (Mermaid), generated from the code and the processing logs:

  * pipeline - built from the pipeline's STEPS list and the validation checks
  * trace    - the recorded steps of one real document

Usage:  python -m app.flowchart          (writes docs/architecture.md)
"""
from __future__ import annotations

import re
from pathlib import Path

from app.config import ROOT_DIR, Settings, get_settings
from app.db import connect, events_for, get_doc
from app.pipeline import STEPS

CHECKS = ["required", "date_valid", "evidence_match", "in_document", "line_math", "items_sum", "total_math",
          "tax_rate", "currency", "model_uncertain", "vendor_known", "number_format", "currency_match", "duplicate"]

CLASSDEFS = """
    classDef io fill:#1C2029,stroke:#E9C46A,color:#F2EDE3
    classDef ai fill:#E9C46A,stroke:#E9C46A,color:#14161B
    classDef code fill:#171A21,stroke:#5A606B,color:#F2EDE3
    classDef ok fill:#18291F,stroke:#7BC59A,color:#CFEBDA
    classDef warn fill:#2A2416,stroke:#E9C46A,color:#F5E6BF
    classDef bad fill:#2D1A17,stroke:#E4735C,color:#F6D2CA
    classDef human fill:#1A2232,stroke:#8FB3E8,color:#D6E4F8"""


def _safe(t, n=70) -> str:
    t = re.sub(r"\s+", " ", str(t or "")).strip().replace('"', "'").replace("<", "(").replace(">", ")").replace("#", "no. ")
    return t if len(t) <= n else t[: n - 1] + "…"


def pipeline_mermaid(settings: Settings | None = None) -> str:
    l = ["flowchart TD", '    IN(["Invoice: PDF, scan or photo"])']
    ids = {s[0]: s[0].upper() for s in STEPS}
    for sid, label, guard in STEPS:
        if sid == "route":
            continue
        l.append(f'    {ids[sid]}["{_safe(label)}<br/><small>{_safe(guard, 80)}</small>"]')
    l += ["    IN --> INGEST", "    INGEST --> EXTRACT", "    EXTRACT --> VALIDATE",
          '    subgraph CK["Checks in code"]']
    l += [f'        C_{c}["{c}"]' for c in CHECKS]
    l += ["    end", "    VALIDATE --> CK", '    ROUTE{"Every field passed?"}', "    CK --> ROUTE",
          '    AUTO["Auto-approved"]', '    HUMAN["Human review: fields highlighted, edit and approve"]',
          "    ROUTE -- yes --> AUTO", "    ROUTE -- no --> HUMAN", "    AUTO --> EXPORT", "    HUMAN --> EXPORT",
          '    OUT[("invoices.csv + invoices.xlsx")]', "    EXPORT --> OUT", CLASSDEFS,
          "    class IN,OUT io", "    class EXTRACT ai", "    class INGEST,VALIDATE,EXPORT,ROUTE code",
          "    class " + ",".join(f"C_{c}" for c in CHECKS) + " code", "    class AUTO ok", "    class HUMAN human",
          "    style CK fill:#111318,stroke:#2A2F38,color:#9097A3"]
    return "\n".join(l)


def trace_mermaid(settings: Settings, doc_id: int) -> str | None:
    conn = connect(settings.db_path)
    try:
        doc, events = get_doc(conn, doc_id), events_for(conn, doc_id)
    finally:
        conn.close()
    if not doc or not events:
        return None
    l = ["flowchart TD", f'    D(["{_safe(doc["filename"], 40)}"])']
    prev, cls = "D", {"ok": [], "warn": [], "bad": [], "human": []}
    for i, e in enumerate(events, 1):
        nid = f"E{i}"
        l.append(f'    {nid}["{e["step"]}<br/><small>{_safe(e["detail"], 70)}, {e["duration_ms"] / 1000:.1f}s</small>"]')
        l.append(f"    {prev} --> {nid}")
        cls["human" if e["step"] == "human_review" else {"ok": "ok", "warning": "warn", "failed": "bad"}.get(e["status"], "ok")].append(nid)
        prev = nid
    l += [f'    R(["{_safe(doc["status"].replace("_", " "))}"])', f"    {prev} --> R", CLASSDEFS, "    class D,R io"]
    l += [f"    class {','.join(v)} {k}" for k, v in cls.items() if v]
    return "\n".join(l)


def latest_doc_id(settings: Settings) -> int | None:
    conn = connect(settings.db_path)
    try:
        r = conn.execute("SELECT id FROM documents WHERE status NOT IN ('new','processing') "
                         "ORDER BY (status='needs_review') DESC, updated_at DESC LIMIT 1").fetchone()
        return r["id"] if r else None
    finally:
        conn.close()


def write_docs(settings: Settings | None = None, path: Path | None = None) -> Path:
    path = path or ROOT_DIR / "docs" / "architecture.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# Folio architecture\n\nGenerated by `python -m app.flowchart` from the pipeline code.\n\n"
                    "```mermaid\n" + pipeline_mermaid(settings) + "\n```\n", encoding="utf-8")
    return path


if __name__ == "__main__":
    print(f"Wrote {write_docs(get_settings())}")
